FORMAT=1
MAX_DATABASE=512*1024*1024
MAX_ARCHIVE=MAX_DATABASE+1024*1024
COUNTS=('projects','project_steps','project_links','tasks','runs','events','snoozes','learning_progress','learning_profiles','publication_receipts')
EXCLUDED='Программа, зависимости, журналы, временные файлы, прежние копии, Windows-автозапуск и служебные файлы устройства не включены. Ссылки на внешние файлы сохраняются как текст; сами файлы не копируются.'
DEVICE_KEYS=('window_geometry','topmost','location_refresh_on_start','backup_state')
REQUIRED_COLUMNS={
    'settings':'key value','revision':'id value','publication_receipts':'dedupe',
    'events':'id title body category created seen dedupe task_id run_id action_state root_id delivered target',
    'tasks':'id name kind enabled schedule config policy grace_seconds max_attempts retry_seconds created',
    'runs':'id task_id slot scheduled_at status attempts started finished retry_at lease_until owner error summary recoveries',
    'snoozes':'id root_id event_id due status',
    'projects':'id title category state notes created updated reminder_task_id',
    'project_steps':'id project_id title done position','project_links':'id project_id label url',
    'learning_progress':'course_id lesson_id state answer notes hints_revealed solution_revealed assessment updated content_version',
    'learning_profiles':'course_id active_lesson platform server_version'}


def digest(path):
    with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()


def profile_id(path):
    with closing(sqlite3.connect(Path(path).resolve().as_uri()+'?mode=ro',uri=True)) as db:
        row=db.execute("SELECT value FROM settings WHERE key='profile_uuid'").fetchone()
        value=json.loads(row[0]) if row else None
    if not isinstance(value,str) or not re.fullmatch('[0-9a-f]{32}',value):raise ValueError('В копии отсутствует идентификатор профиля.')
    return value


def validate_destination(folder,home):
    if not folder or not Path(folder).is_absolute():raise ValueError('Выберите абсолютный путь к папке резервных копий.')
    path=Path(folder)
    if not path.is_dir() or path.is_symlink() or path.is_junction() or path.resolve()==Path(home).resolve():
        raise ValueError('Выберите существующую отдельную папку без ссылки или junction.')
    # A real exclusive creation checks access and does not replace a user file.
    with tempfile.TemporaryFile(dir=path):pass
    return path.resolve()


def device_id(home):
    path=Path(home)/'.backup-device.json'
    if path.is_symlink():raise ValueError('Invalid device file')
    if path.exists():return json.loads(path.read_text(encoding='utf-8'))['id']
    value=uuid4().hex
    try:
        with path.open('x',encoding='utf-8') as stream:json.dump({'id':value},stream)
    except FileExistsError:return json.loads(path.read_text(encoding='utf-8'))['id']
    return value


def inspect_database(path):
    import desktop_store as store
    check_database(path)
    with closing(sqlite3.connect(Path(path).resolve().as_uri()+'?mode=ro',uri=True)) as db:
        db.execute('PRAGMA trusted_schema=OFF')
        schema=db.execute('PRAGMA user_version').fetchone()[0]
        if db.execute('PRAGMA foreign_key_check').fetchone():raise ValueError('Нарушены ссылки в базе копии.')
        if schema!=store.SCHEMA_VERSION:raise ValueError('Схема копии не поддерживается этой версией Орбиты.')
        for table,columns in REQUIRED_COLUMNS.items():
            actual={row[1] for row in db.execute('PRAGMA table_info('+table+')')}
            if not set(columns.split()).issubset(actual):raise ValueError('Неполная структура базы копии.')
        if not db.execute('SELECT value FROM revision WHERE id=1').fetchone():raise ValueError('Отсутствует версия изменений профиля.')
        # No executable schema from an imported archive: only the exact current
        # tables, indexes and revision triggers generated by Orbita are accepted.
        objects=list(db.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL"))
        allowed=set(COUNTS)|{'settings','revision','sqlite_sequence'}
        for kind,name,table,sql in objects:
            if kind=='table' and (name not in allowed or 'VIRTUAL' in sql.upper()):raise ValueError('Неизвестная таблица в копии.')
            if kind=='view':raise ValueError('Представления в копии не поддерживаются.')
            if kind=='trigger':
                match=re.fullmatch(r'rev_(\w+)_(INSERT|UPDATE|DELETE)',name)
                if not match or match[1] not in allowed:raise ValueError('Неизвестный триггер в копии.')
                expected=f'CREATE TRIGGER {name} AFTER {match[2]} ON {table} BEGIN UPDATE revision SET value=value+1 WHERE id=1; END'
                normalize=lambda s:' '.join(s.replace('IF NOT EXISTS ','').split()).casefold()
                if normalize(sql)!=normalize(expected):raise ValueError('Изменённый триггер в копии.')
        counts={table:db.execute('SELECT COUNT(*) FROM '+table).fetchone()[0] for table in COUNTS}
        for key,value in db.execute('SELECT key,value FROM settings'):json.loads(value)
        from automation_models import validate_schedule
        for kind,schedule,config in db.execute('SELECT kind,schedule,config FROM tasks'):
            if kind not in ('weather','audit','reminder','learning','backup'):raise ValueError('Неизвестный сценарий в копии.')
            validate_schedule(json.loads(schedule));json.loads(config)
        return schema,counts


def validated_archive(path,work):
    """Extract a bounded whitelist only; never trust names or claimed counts."""
    path=Path(path);work=Path(work)
    if path.stat().st_size>MAX_ARCHIVE:raise ValueError('Архив слишком большой.')
    with zipfile.ZipFile(path) as archive:
        entries=archive.infolist()
        if len(entries)!=2 or {e.filename for e in entries}!={'manifest.json','inbox.sqlite'}:
            raise ValueError('Недопустимый состав или путь в архиве.')
        for item in entries:
            limit=65536 if item.filename=='manifest.json' else MAX_DATABASE
            if item.is_dir() or item.file_size>limit or item.flag_bits&1 or (item.external_attr>>16)&0o170000==0o120000:
                raise ValueError('Недопустимый размер или тип файла.')
            size=0
            with archive.open(item) as src,(work/item.filename).open('xb') as dst:
                while chunk:=src.read(1024*1024):
                    size+=len(chunk)
                    if size>limit:raise ValueError('Превышен предел распаковки.')
                    dst.write(chunk)
            if size!=item.file_size:raise ValueError('Неполный архив.')
    manifest=json.loads((work/'manifest.json').read_text(encoding='utf-8'))
    if manifest.get('format')!=FORMAT or manifest.get('product')!='orbita-profile':raise ValueError('Формат копии не поддерживается.')
    if not isinstance(manifest.get('app_version'),str) or not re.fullmatch(r'\d+\.\d+\.\d+',manifest['app_version']):raise ValueError('Неверная версия приложения в копии.')
    stamp=datetime.fromisoformat(manifest['created'])
    if stamp.tzinfo is None:raise ValueError('В копии отсутствует часовой пояс даты.')
    database=work/'inbox.sqlite';info=manifest['files']
    if info!={'inbox.sqlite':{'bytes':database.stat().st_size,'sha256':digest(database)}}:raise ValueError('Контрольная сумма копии не совпала.')
    schema,counts=inspect_database(database)
    if manifest.get('profile_id')!=profile_id(database):raise ValueError('Идентификатор копии не соответствует профилю.')
    if manifest.get('schema')!=schema or manifest.get('counts')!=counts:raise ValueError('Описание копии не соответствует базе.')
    return manifest


def preview(path):
    with tempfile.TemporaryDirectory(prefix='orbita-inspect-') as folder:return validated_archive(path,folder)


def _state(home,value):
    import desktop_store as store
    # API is profile-explicit; use raw DB under the already shared/exclusive gate.
    with closing(sqlite3.connect(Path(home)/'inbox.sqlite',timeout=10)) as db,db:
        old=db.execute("SELECT value FROM settings WHERE key='backup_state'").fetchone()
        state=json.loads(old[0]) if old else {}
        state.update(value)
        db.execute('INSERT OR REPLACE INTO settings VALUES(?,?)',('backup_state',json.dumps(state)))


def create(home,folder,automatic=False,keep=7):
    home=Path(home)
    with access(home):
        _state(home,{'state':'running','attempted':datetime.now(timezone.utc).isoformat()})
        try:
            destination=validate_destination(folder,home)
            owner=device_id(home);stamp=datetime.now(timezone.utc).isoformat()
            name=('Orbita-auto-' if automatic else 'Orbita-manual-')+uuid4().hex+'.orbita.zip'
            target=destination/name;temporary=destination/('.'+name+'.part')
            try:
                with tempfile.TemporaryDirectory(prefix='orbita-backup-') as work:
                    work=Path(work);snapshot=work/'inbox.sqlite'
                    database_copy(home/'inbox.sqlite',snapshot)
                    if snapshot.stat().st_size>MAX_DATABASE:raise ValueError('Профиль превышает поддерживаемый размер 512 MiB.')
                    schema,counts=inspect_database(snapshot)
                    manifest={'product':'orbita-profile','format':FORMAT,'app_version':VERSION,'schema':schema,'created':stamp,'profile_id':profile_id(snapshot),
                              'automatic':automatic,'owner':owner,'counts':counts,'excluded':EXCLUDED,
                              'files':{'inbox.sqlite':{'bytes':snapshot.stat().st_size,'sha256':digest(snapshot)}}}
                    with zipfile.ZipFile(temporary,'x',zipfile.ZIP_DEFLATED) as archive:
                        archive.write(snapshot,'inbox.sqlite');archive.writestr('manifest.json',json.dumps(manifest,ensure_ascii=False))
                preview(temporary)
                with temporary.open('r+b') as stream:stream.flush();os.fsync(stream.fileno())
                os.replace(temporary,target)
            finally:temporary.unlink(missing_ok=True)
            if automatic:_retain(home,target,owner,keep)
            _state(home,{'state':'success','last_success':stamp,'last_file':str(target),'error':None})
            return target
        except Exception as exc:
            try:_state(home,{'state':'error','error':type(exc).__name__})
            except (sqlite3.Error,OSError):pass
            raise


def _retain(home,new,owner,keep):
    if type(keep) is not int or not 1<=keep<=100:raise ValueError('Хранить можно от 1 до 100 автоматических копий.')
    ledger=Path(home)/'.auto-backups.json'
    entries=json.loads(ledger.read_text(encoding='utf-8')) if ledger.exists() else []
    entries.append({'file':str(new),'sha256':digest(new)})
    write_json(ledger,entries) # failure here must never trigger deletion
    candidates=[]
    for item in entries:
        p=Path(item['file'])
        if p.parent!=new.parent or not p.name.startswith('Orbita-auto-') or p.is_symlink() or not p.is_file():continue
        try:
            if digest(p)!=item['sha256']:continue
            metadata=preview(p)
            if metadata.get('owner')==owner and metadata.get('automatic') is True:candidates.append(item)
        except (OSError,ValueError,sqlite3.Error,zipfile.BadZipFile):continue
    for item in candidates[:-keep]:
        try:Path(item['file']).unlink();entries.remove(item)
        except OSError:pass
    write_json(ledger,entries)


def restore(home,archive,pause=True,checkpoint=None):
    """Caller must stop all in-process workers/readers and restart after success."""
    from profile_recovery import cleanup,recover_locked
    home=Path(home);checkpoint=checkpoint or (lambda phase:None)
    with tempfile.TemporaryDirectory(prefix='orbita-restore-') as temp:
        metadata=validated_archive(archive,temp)
        with access(home,True):
            folder=home/'.restore'
            if folder.is_symlink() or folder.is_junction():raise ValueError('Папка восстановления не должна быть ссылкой.')
            folder.mkdir(exist_ok=True)
            for name in ('previous.sqlite','incoming.sqlite','journal.json','journal.writing'):
                if (folder/name).is_symlink() or (folder/name).is_junction():raise ValueError('Ссылка в служебной папке восстановления.')
            # An independent, verified, user-readable insurance archive first.
            safety=home/'backups';safety.mkdir(exist_ok=True)
            insurance=create(home,safety)
            database_copy(home/'inbox.sqlite',folder/'previous.sqlite');check_database(folder/'previous.sqlite')
            checkpoint('insurance')
            database_copy(Path(temp)/'inbox.sqlite',folder/'incoming.sqlite')
            with closing(sqlite3.connect(folder/'incoming.sqlite')) as db,db, closing(sqlite3.connect(home/'inbox.sqlite')) as current:
                local={k:v for k,v in current.execute('SELECT key,value FROM settings') if k in DEVICE_KEYS}
                for key in DEVICE_KEYS:db.execute('DELETE FROM settings WHERE key=?',(key,))
                for key,value in local.items():db.execute('INSERT INTO settings VALUES(?,?)',(key,value))
                if 'topmost' not in local:db.execute("INSERT INTO settings VALUES('topmost','false')")
                db.execute("INSERT OR REPLACE INTO settings VALUES('location_refresh_on_start','false')")
                db.execute("INSERT OR REPLACE INTO settings VALUES('paused',?)",(json.dumps(bool(pause)),))
                # Imported device paths never become an automatic write target.
                for task_id,config in db.execute("SELECT id,config FROM tasks WHERE kind='backup'").fetchall():
                    config=json.loads(config);config['folder']=''
                    db.execute('UPDATE tasks SET config=?,enabled=0 WHERE id=?',(json.dumps(config),task_id))
                    db.execute("UPDATE runs SET status='cancelled',lease_until=NULL,summary='После восстановления требуется выбрать папку копий' WHERE task_id=? AND status IN ('queued','retry','running')",(task_id,))
                # Preserve inbox/history but do not replay a wall of old toasts.
                db.execute('UPDATE events SET delivered=1')
                # Keep terminal slot receipts from this device as well: restoring
                # yesterday's snapshot must not repeat today's completed actions.
                current_identity=current.execute("SELECT value FROM settings WHERE key='profile_uuid'").fetchone()
                if current_identity and json.loads(current_identity[0])==metadata['profile_id']:
                    for row in current.execute("SELECT task_id,slot,scheduled_at,status,finished FROM runs WHERE status IN ('success','failed','skipped','cancelled')"):
                        if not db.execute('SELECT 1 FROM tasks WHERE id=?',(row[0],)).fetchone():continue
                        db.execute('INSERT OR IGNORE INTO runs(task_id,slot,scheduled_at,status,finished) VALUES(?,?,?,?,?)',tuple(row))
                        db.execute("UPDATE runs SET status=?,finished=?,lease_until=NULL,owner=NULL WHERE task_id=? AND slot=? AND status IN ('running','queued','retry')",(row[3],row[4],row[0],row[1]))
                    for key, in current.execute('SELECT dedupe FROM publication_receipts'):
                        db.execute('INSERT OR IGNORE INTO publication_receipts VALUES(?)',(key,))
                    for key, in current.execute("SELECT dedupe FROM events WHERE action_state='done' AND dedupe IS NOT NULL"):
                        db.execute("UPDATE events SET action_state='done' WHERE dedupe=?",(key,))
                    for key,due,status in current.execute("SELECT e.dedupe,s.due,s.status FROM snoozes s JOIN events e ON e.id=s.event_id WHERE s.status!='pending' AND e.dedupe IS NOT NULL"):
                        db.execute('UPDATE snoozes SET status=? WHERE due=? AND event_id IN (SELECT id FROM events WHERE dedupe=?)',(status,due,key))
                db.execute("UPDATE snoozes SET status='cancelled' WHERE root_id IN (SELECT id FROM events WHERE action_state='done')")
                db.execute("UPDATE runs SET lease_until=? WHERE status='running'",(datetime.now(timezone.utc).isoformat(),))
            check_database(folder/'incoming.sqlite')
            journal={'format':1,'phase':'prepared'};write_json(folder/'journal.json',journal)
            try:
                checkpoint('prepared')
                journal['phase']='applying';write_json(folder/'journal.json',journal)
                checkpoint('applying')
                database_copy(folder/'incoming.sqlite',home/'inbox.sqlite')
                check_database(home/'inbox.sqlite');checkpoint('applied')
                journal['phase']='committed';write_json(folder/'journal.json',journal)
            except BaseException:
                recover_locked(home)
                raise
            cleanup(home)
            return {'insurance':str(insurance),'source':metadata,'paused':pause}
